export type CopyKey = keyof typeof EN;

export function c(lang: Lang, key: CopyKey, vars: Record<string, string | number> = {}): string {
    const base = (lang === 'es' ? ES : EN)[key];
    return base.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

export function money(n: number, lang: Lang = 'en'): string {
    return `$${Math.round(n).toLocaleString(lang === 'es' ? 'es-US' : 'en-US')}`;
}
